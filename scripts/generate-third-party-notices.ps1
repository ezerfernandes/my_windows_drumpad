# Generates third-party license notices from the resolved Cargo dependency graph.
#
# Run from anywhere:
#   pwsh ./scripts/generate-third-party-notices.ps1
#
# The output is committed and also copied into the portable ZIP at package time.

[CmdletBinding()]
param(
    [string]$OutputPath = (Join-Path $PSScriptRoot "..\docs\release\THIRD_PARTY_NOTICES.md")
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
Push-Location $repoRoot
try {
    $metadataJson = & cargo metadata --format-version 1 --locked
    if ($LASTEXITCODE -ne 0) {
        throw "cargo metadata failed with exit code $LASTEXITCODE"
    }
    $metadata = $metadataJson | ConvertFrom-Json

    $workspaceIds = @{}
    foreach ($member in $metadata.workspace_members) {
        $workspaceIds[$member] = $true
    }

    function Get-LicenseText {
        param($Package)
        foreach ($propertyName in @("license", "license_expression")) {
            $property = $Package.PSObject.Properties[$propertyName]
            if ($null -ne $property -and -not [string]::IsNullOrWhiteSpace([string]$property.Value)) {
                return [string]$property.Value
            }
        }
        return "No license field; see the package repository"
    }

    $packages = $metadata.packages |
        Where-Object { -not $workspaceIds.ContainsKey($_.id) } |
        Sort-Object name, version

    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add("# Third-party notices")
    $lines.Add("")
    $lines.Add("Drumpad is licensed under MIT OR Apache-2.0. It depends on the following")
    $lines.Add("third-party crates, grouped by package name. The license identifier comes from")
    $lines.Add("each package's Cargo metadata; full license texts are available in the crate")
    $lines.Add("source or at the listed repository.")
    $lines.Add("")
    $lines.Add("Generated by ``scripts/generate-third-party-notices.ps1`` from the locked")
    $lines.Add("dependency graph. Do not edit by hand.")
    $lines.Add("")

    $currentName = $null
    foreach ($package in $packages) {
        if ($package.name -ne $currentName) {
            $currentName = $package.name
            $lines.Add("")
            $lines.Add("## $currentName")
            $lines.Add("")
        }

        $license = Get-LicenseText -Package $package
        $repositoryProperty = $package.PSObject.Properties["repository"]
        $repository = if ($null -ne $repositoryProperty) { [string]$repositoryProperty.Value } else { "" }
        if ([string]::IsNullOrWhiteSpace($repository)) {
            $lines.Add("- ``$($package.name)`` $($package.version) - $license")
        }
        else {
            $lines.Add("- ``$($package.name)`` $($package.version) - $license - $repository")
        }
    }

    $lines.Add("")

    $directory = Split-Path -Parent $OutputPath
    New-Item -ItemType Directory -Force -Path $directory | Out-Null
    Set-Content -Path $OutputPath -Value $lines -Encoding utf8

    $count = @($packages).Count
    Write-Host "Wrote $OutputPath ($count third-party packages)"
}
finally {
    Pop-Location
}
